-- 1) Livros (acervo)
create table if not exists public.livros (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  titulo text not null,
  autor text not null,
  status text not null default 'disponivel' check (status in ('disponivel', 'emprestado')),
  previsao_devolucao date null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint chk_livros_titulo check (char_length(trim(titulo)) >= 2),
  constraint chk_livros_autor check (char_length(trim(autor)) >= 2),
  constraint chk_livros_codigo check (char_length(trim(codigo)) >= 2)
);

-- 2) Leitores
create table if not exists public.leitores (
  id bigint generated by default as identity primary key,
  nome text not null,
  telefone text not null,
  created_at timestamptz not null default now(),
  constraint chk_leitores_nome check (char_length(trim(nome)) >= 2),
  constraint chk_leitores_telefone check (char_length(trim(telefone)) >= 8)
);

-- 3) Empréstimos
create table if not exists public.emprestimos (
  id bigint generated by default as identity primary key,
  livro_id bigint not null references public.livros(id) on delete restrict,
  leitor_id bigint not null references public.leitores(id) on delete restrict,
  data_retirada date not null default current_date,
  prazo_devolucao date not null,
  data_devolucao date null,
  status text not null default 'em_dia' check (status in ('em_dia', 'atrasado', 'devolvido')),
  created_at timestamptz not null default now(),
  constraint chk_emprestimos_prazo check (prazo_devolucao >= data_retirada)
);

create index if not exists idx_livros_status on public.livros(status);
create index if not exists idx_livros_titulo on public.livros(titulo);
create index if not exists idx_emprestimos_livro on public.emprestimos(livro_id);
create index if not exists idx_emprestimos_leitor on public.emprestimos(leitor_id);
create index if not exists idx_emprestimos_status on public.emprestimos(status);

-- Atualização automática de updated_at em livros
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_livros_updated_at on public.livros;
create trigger trg_livros_updated_at
before update on public.livros
for each row execute function public.set_updated_at();

